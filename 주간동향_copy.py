# 💡 텍스트를 깨끗하게 정제하고 불용어를 걷어내는 공통 함수 정의 (안정성 확보)
def clean_and_filter_tokens(text_data_list):
    if not text_data_list:
        return []
    # 텍스트 병합 및 소문자화
    all_text = " ".join(text_data_list).lower()
    # 특수문자 및 불필요 문장 기호 완벽 공백 치환
    for punc in ['[', ']', '(', ')', ',', '.', '?', '!', '"', "'", '·', ':', ';', '-', '_']:
        all_text = all_text.replace(punc, ' ')
    
    words = all_text.split()
    # 공백 제거 및 2글자 이상 + 글로벌 불용어 차단망 적용
    filtered = [w.strip() for w in words if len(w.strip()) >= 2 and w.strip() not in GLOBAL_STOPWORDS]
    return filtered

